#!/usr/bin/env python3
"""Reproduce the native Bone Lab pose atlas (no external inputs)."""
import argparse
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / 'src/generated/pose_atlas.S'
YAW = range(-180, 181, 5)
PITCH = range(-180, 181, 6)
FLEX = range(0, 181, 6)


def rows():
    for yaw in YAW:
        cy, sy = math.cos(math.radians(yaw)), math.sin(math.radians(yaw))
        for pitch in PITCH:
            cp, sp = math.cos(math.radians(pitch)), math.sin(math.radians(pitch))
            for flex in FLEX:
                cl = math.cos(math.radians(pitch - flex))
                sl = math.sin(math.radians(pitch - flex))
                yield (yaw, pitch, flex, cp * cy, cp * sy, sp, cl * cy, cl * sy, sl)


def lines():
    yield '// Generated by tools/generate_atlas.py; do not edit.\n'
    yield '// Each pose: yaw, pitch, flex, upper unit XYZ, lower unit XYZ.\n'
    yield '.section .rodata\n.balign 64\n'
    yield '.global pose_atlas_start\n.hidden pose_atlas_start\n'
    yield '.type pose_atlas_start,@object\npose_atlas_start:\n'
    for row in rows():
        for value in row:
            yield f'.double {float(value):.17g}\n'
    yield '.global pose_atlas_end\n.hidden pose_atlas_end\npose_atlas_end:\n'
    yield '.size pose_atlas_start,pose_atlas_end-pose_atlas_start\n'
    yield '.section .note.GNU-stack,"",@progbits\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='verify exact generated bytes')
    args = parser.parse_args()
    expected = ''.join(lines())
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != expected:
            parser.exit(1, 'Pose atlas differs; run tools/generate_atlas.py\n')
        print('Pose atlas is reproducible: 138043 records, 1242387 .double directives')
    else:
        OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        OUTPUT.write_text(expected)
        print(f'Wrote {OUTPUT}: 138043 poses; 9939096 data bytes')

if __name__ == '__main__':
    main()
